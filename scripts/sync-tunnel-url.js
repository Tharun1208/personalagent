/**
 * sync-tunnel-url.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Reads the Cloudflare tunnel URL from scripts/tunnel.log and writes it into
 * capacitor.config.ts — so the Android APK can work on ANY network (4G, 5G,
 * different Wi-Fi, office, home, etc.), not just the local Wi-Fi.
 *
 * Usage:
 *   1. Start tunnel:   scripts\start-tunnel.bat   (or: cloudflared tunnel --url http://localhost:3000)
 *   2. Start server:   npm run dev
 *   3. Run this:       node scripts/sync-tunnel-url.js
 *   4. Sync android:   npx cap sync
 *   5. Build APK:      cd android && .\gradlew assembleDebug
 *
 * Or all-in-one:       npm run cap:sync:tunnel
 */

const fs   = require('fs');
const path = require('path');

const LOG_FILE    = path.join(__dirname, 'tunnel.log');
const CONFIG_FILE = path.join(__dirname, '..', 'capacitor.config.ts');

// ── 1. Read tunnel log and extract the public URL ────────────────────────────
if (!fs.existsSync(LOG_FILE)) {
  console.error('❌  tunnel.log not found.');
  console.error('   Start the tunnel first:  .\\scripts\\start-tunnel.bat');
  process.exit(1);
}

const logContent = fs.readFileSync(LOG_FILE, 'utf8');

// Match lines like: https://something.trycloudflare.com
const urlMatch = logContent.match(/https:\/\/[a-z0-9-]+\.trycloudflare\.com/g);

if (!urlMatch) {
  console.error('❌  No Cloudflare tunnel URL found in tunnel.log.');
  console.error('   Make sure the tunnel is running: .\\scripts\\start-tunnel.bat');
  process.exit(1);
}

// The last match is the most recent tunnel URL
const tunnelUrl = urlMatch[urlMatch.length - 1];

console.log(`\n🌐  Cloudflare tunnel URL : ${tunnelUrl}`);

// ── 2. Write capacitor.config.ts ─────────────────────────────────────────────
const configContent = `import type { CapacitorConfig } from '@capacitor/cli';

/**
 * AUTO-GENERATED by scripts/sync-tunnel-url.js
 * Do not edit manually — run \`npm run cap:sync:tunnel\` to regenerate.
 *
 * Tunnel URL : ${tunnelUrl}
 * Generated  : ${new Date().toISOString()}
 *
 * This URL works on ANY network (4G, 5G, any Wi-Fi).
 * The tunnel securely forwards traffic to your local Next.js server.
 */
const config: CapacitorConfig = {
  appId: 'com.assistance.ai',
  appName: 'Personal Agent',
  webDir: 'public',
  server: {
    // Public Cloudflare tunnel URL — works on all networks globally
    url: '${tunnelUrl}',
    cleartext: false,
    androidScheme: 'https',
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 2000,
      backgroundColor: '#0c111d',
      showSpinner: false,
    },
  },
};

export default config;
`;

fs.writeFileSync(CONFIG_FILE, configContent, 'utf8');
console.log(`✅  capacitor.config.ts updated with tunnel URL`);
console.log(`\n📱  Next steps:`);
console.log(`    npx cap sync`);
console.log(`    cd android && .\\gradlew assembleDebug`);
console.log(`    → APK works on any network!\n`);
