/**
 * sync-local-ip.js
 * ─────────────────────────────────────────────────────────────────────────────
 * Detects the machine's current LAN IPv4 address and rewrites
 * capacitor.config.ts so the Android (Capacitor) app connects to it.
 *
 * Usage:
 *   node scripts/sync-local-ip.js          → uses port 3000 (default)
 *   node scripts/sync-local-ip.js 4000     → uses port 4000
 *
 * Then run:  npx cap sync
 * Or simply: npm run cap:sync:local
 */

const os = require('os');
const fs = require('fs');
const path = require('path');

const PORT = process.argv[2] || '3000';

// ── 1. Find local LAN IP ──────────────────────────────────────────────────────
function getLocalIP() {
  const interfaces = os.networkInterfaces();
  for (const [, addrs] of Object.entries(interfaces)) {
    if (!addrs) continue;
    for (const addr of addrs) {
      if (addr.family === 'IPv4' && !addr.internal) {
        return addr.address;
      }
    }
  }
  return '127.0.0.1'; // fallback
}

const localIP = getLocalIP();
const serverUrl = `http://${localIP}:${PORT}`;

console.log(`\n🌐  Detected local IP : ${localIP}`);
console.log(`🔗  Server URL        : ${serverUrl}`);

// ── 2. Write capacitor.config.ts ──────────────────────────────────────────────
const configPath = path.join(__dirname, '..', 'capacitor.config.ts');

const configContent = `import type { CapacitorConfig } from '@capacitor/cli';

/**
 * AUTO-GENERATED by scripts/sync-local-ip.js
 * Do not edit manually — run \`npm run cap:sync:local\` to regenerate.
 *
 * Server URL: ${serverUrl}
 * Generated : ${new Date().toISOString()}
 */
const config: CapacitorConfig = {
  appId: 'com.assistance.ai',
  appName: 'Personal Agent',
  webDir: 'public',
  server: {
    // Points the Android WebView to the Next.js dev server on the LAN.
    // Change to your Vercel/production URL for a release build.
    url: '${serverUrl}',
    cleartext: true,          // allow http (needed for local IP)
    androidScheme: 'http',
  },
  plugins: {
    SplashScreen: {
      launchShowDuration: 2000,
      backgroundColor: '#0c111d',
      showSpinner: false,
    },
  },
};

export default config;
`;

fs.writeFileSync(configPath, configContent, 'utf8');
console.log(`✅  capacitor.config.ts updated → ${configPath}\n`);
